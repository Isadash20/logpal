import type { Recipe } from '../types'

/**
 * Recipes written for LogPal.
 *
 * The USDA catalogue is public-domain, well-tested and free to ship, and its
 * ceiling is about 575 calories — it is a public-health library, so it does not
 * publish anything calorie-dense. That leaves everyone eating to gain with
 * nothing, and no amount of re-sorting fixes a gap in the source.
 *
 * So these are ours: substantial, protein-forward, and written to be worth
 * cooking rather than worth citing. Neither MyFitnessPal's library nor Samsung
 * Food's could be used here — the first is paywalled licensed content, the
 * second is user-uploaded with rights retained by the uploaders — which is the
 * whole reason this file exists.
 *
 * `nutritionPerServing` is stated rather than derived. The ingredient parser is
 * good enough to price a shopping list and not good enough to be the number on
 * the card, and these are written to hit particular targets, so the targets are
 * what they carry. Photographs are fetched from Wikimedia Commons under CC0 or
 * public domain by `scripts/fetch-photos.mjs`, which fills in `imageUrl` and
 * `photoCredit`.
 */

interface Authored extends Recipe {
  /** What to look for on Commons. Consumed by the photo script. */
  photoQuery?: string
}

/** Photographer and licence, shown on the recipe. Their work, their credit. */
export const PHOTO_CREDITS: Record<string, string> = {}

function r(a: {
  id: string
  name: string
  description: string
  servings: number
  prep: number
  cook: number
  tags: string[]
  ingredients: string[]
  steps: string[]
  n: { calories: number; protein: number; carbs: number; fat: number; satFat: number; fiber: number; sugar: number; sodium: number }
  photo: string
  imageUrl?: string
  photoCredit?: string
}): Authored {
  if (a.imageUrl && a.photoCredit) PHOTO_CREDITS[`own_${a.id}`] = a.photoCredit
  return {
    id: `own_${a.id}`,
    name: a.name,
    description: a.description,
    servingsMade: a.servings,
    prepMin: a.prep,
    cookMin: a.cook,
    tags: a.tags,
    ingredients: a.ingredients,
    steps: a.steps,
    items: [],
    createdAt: 0,
    nutritionPerServing: { ...a.n, cholesterol: 0 },
    photoQuery: a.photo,
    imageUrl: a.imageUrl,
  }
}

